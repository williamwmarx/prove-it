// Regenerates the static class and package facts of the native front end's modeled parent runtime
// (tla-front/src/java_parent): the class entries of the pinned tla2tools.jar and the packages of
// every system module of the pinned JDK, which scripts/java-parent/JdkFacts.java reads, with
// provenance.json recording what they came from. See scripts/java-parent/README.md.
// Usage: bun scripts/java-parent.ts --jar <tla2tools.jar> --jdk <pinned JDK> --tlc-source <tlaplus>
//   [--output <directory>]

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";

const PINNED_TLC = "d8fb231de4e4b5d02c1b2ed1ac759c086f694021";
const PINNED_JDK = "21.0.13+9-LTS";
const MODULE_DESCRIPTORS = ["module-info.class", "META-INF/versions/9/module-info.class"];

const { values } = parseArgs({
  options: {
    jar: { type: "string" },
    jdk: { type: "string" },
    "tlc-source": { type: "string" },
    output: {
      type: "string",
      default: join(import.meta.dirname, "../native/crates/tla-front/src/java_parent"),
    },
  },
});
if (!values.jar || !values.jdk || !values["tlc-source"]) {
  console.error("Usage: bun scripts/java-parent.ts --jar <jar> --jdk <jdk> --tlc-source <tlaplus>");
  process.exit(1);
}
const jar = resolve(values.jar);
const jdk = resolve(values.jdk);
const source = resolve(values["tlc-source"]);
const output = resolve(values.output);

const sha = (data: string | Uint8Array) => createHash("sha256").update(data).digest("hex");

const run = (command: string, args: string[]) => {
  const result = spawnSync(command, args, { maxBuffer: 1 << 28 });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed: ${result.stderr.toString()}`);
  }
  return result.stdout;
};
const facts = (...args: string[]) =>
  run(join(jdk, "bin/java"), [
    "--source",
    "21",
    join(import.meta.dirname, "java-parent/JdkFacts.java"),
    ...args,
  ]);
const lines = (bytes: Uint8Array) =>
  new TextDecoder()
    .decode(bytes)
    .split("\n")
    .filter((line) => line !== "");
// Sorted by code point, as the names are ASCII.
const sorted = (names: Iterable<string>) => [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const commit = run("git", ["-C", source, "rev-parse", "HEAD"]).toString().trim();
if (commit !== PINNED_TLC) throw new Error(`TLC source ${commit}, expected ${PINNED_TLC}`);
const release = readFileSync(join(jdk, "release"));
const properties = new Map(
  release
    .toString()
    .split("\n")
    .filter((line) => line.includes("="))
    .map((line) => {
      const at = line.indexOf("=");
      return [line.slice(0, at), line.slice(at + 1).replace(/^"+|"+$/g, "")] as const;
    }),
);
const pinned = {
  JAVA_RUNTIME_VERSION: PINNED_JDK,
  IMPLEMENTOR: "Eclipse Adoptium",
  OS_NAME: "Linux",
  OS_ARCH: "x86_64",
};
if (Object.entries(pinned).some(([key, value]) => properties.get(key) !== value)) {
  throw new Error("a different pinned JDK build, vendor, or platform");
}

const entries = sorted(lines(facts("entries", jar)).filter((name) => name.endsWith(".class")));
if (new Set(entries).size !== entries.length) throw new Error("duplicate jar class entries");
const excluded = entries.filter((name) => MODULE_DESCRIPTORS.includes(name));
if (entries.some((name) => name.startsWith("META-INF/") && !excluded.includes(name))) {
  throw new Error("unmodeled multi-release class selection");
}
const classes = sorted(
  new Set(
    entries
      .filter((name) => !excluded.includes(name))
      .map((name) => name.slice(0, -".class".length).replaceAll("/", ".")),
  ),
);
const manifest = facts("read", jar, "META-INF/MANIFEST.MF");

const modules = new Map<string, string[]>();
const packageLines = lines(facts("packages"));
for (const line of packageLines) if (!line.includes("\t")) modules.set(line, []);
for (const line of packageLines) {
  const at = line.indexOf("\t");
  if (at >= 0) modules.get(line.slice(0, at))?.push(line.slice(at + 1));
}
const releaseModules = new Set((properties.get("MODULES") ?? "").split(/\s+/).filter(Boolean));
if (
  releaseModules.size !== modules.size ||
  [...modules.keys()].some((name) => !releaseModules.has(name))
) {
  throw new Error("module finder differs from the pinned release module list");
}
const packages = sorted(new Set([...modules.values()].flat()));
if (packages.includes("")) throw new Error("an unmodeled JDK root package");

mkdirSync(output, { recursive: true });
const table = (name: string, names: string[]) =>
  `pub(super) const ${name}: &[&str] = &[\n${names.map((value) => `    ${JSON.stringify(value)},\n`).join("")}];\n`;
const generated = `// Generated by scripts/java-parent.ts; see provenance.json.\n\n${table("TLC_CLASSES", classes)}\n${table("JDK_PACKAGES", packages)}`;
writeFileSync(join(output, "data.rs"), generated);
const entriesText = entries.map((name) => `${name}\n`).join("");
writeFileSync(join(output, "tlc-class-entries.txt"), entriesText);
const packagesText = packages.map((name) => `${name}\n`).join("");
writeFileSync(join(output, "jdk-module-packages.txt"), packagesText);
const proxy = facts("read", join(jdk, "lib/src.zip"), "java.base/java/lang/reflect/Proxy.java");
const reflect = facts(
  "read",
  join(jdk, "lib/src.zip"),
  "java.base/sun/reflect/misc/ReflectUtil.java",
);
const jmods = sorted(readdirSync(join(jdk, "jmods")).filter((name) => name.endsWith(".jmod")));
const provenance = {
  schema: 1,
  contract:
    "Pinned TLC master and Temurin JDK21, before any user classloader mutation; no extra or manifest-companion parent jars. Never inferred from Default alone.",
  tlc: {
    source_commit: commit,
    jar_sha256: sha(readFileSync(jar)),
    jar_manifest_sha256: sha(manifest),
    class_entry_count: entries.length,
    binary_name_count: classes.length,
    class_entries_sha256: sha(entriesText),
    excluded_module_descriptors: excluded,
    manifest_class_path: "CommunityModules-deps.jar CommunityModules.jar",
  },
  jdk: {
    runtime_version: PINNED_JDK,
    implementor: properties.get("IMPLEMENTOR"),
    os_name: properties.get("OS_NAME"),
    os_arch: properties.get("OS_ARCH"),
    release_sha256: sha(release),
    runtime_image_sha256: sha(readFileSync(join(jdk, "lib/modules"))),
    module_count: modules.size,
    package_count: packages.length,
    packages_sha256: sha(packagesText),
    module_packages: Object.fromEntries(modules),
    jmod_sha256: Object.fromEntries(
      jmods.map((name) => [name, sha(readFileSync(join(jdk, "jmods", name)))]),
    ),
  },
  dynamic_proxy_guard: {
    source:
      "java.base/java/lang/reflect/Proxy.java:838-852,904-919; sun/reflect/misc/ReflectUtil.java PROXY_PACKAGE",
    proxy_source_sha256: sha(proxy),
    reflect_util_source_sha256: sha(reflect),
    unknown_packages: ["jdk.proxy<decimal>", "com.sun.proxy.jdk.proxy<decimal>"],
  },
  generated_data_sha256: sha(generated),
};
writeFileSync(join(output, "provenance.json"), `${JSON.stringify(provenance, null, 2)}\n`);
console.log(
  JSON.stringify({
    tlc_classes: classes.length,
    jdk_modules: modules.size,
    jdk_packages: packages.length,
    data_bytes: Buffer.byteLength(generated),
  }),
);
