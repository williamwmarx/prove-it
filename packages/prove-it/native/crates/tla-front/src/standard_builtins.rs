//! The operators that tla-ts implements natively for each TLC version, with the arities of their
//! parameters and their ranges.

/// A builtin's flags: state-level, level-constant, lazy, Naturals' >=, a method of Naturals, as
/// the IR writes them.
pub struct StandardOperator {
    pub name: &'static str,
    pub arity: usize,
    pub flags: u32,
    pub params: Option<&'static [usize]>,
    pub range: Option<[u32; 4]>,
}

pub struct StandardModule {
    pub name: &'static str,
    pub extends: &'static [&'static str],
    pub operators: &'static [StandardOperator],
}

